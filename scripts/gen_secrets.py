#!/usr/bin/env python3
"""Generate every missing `by: generated` secret of secrets.manifest.yaml INTO Infisical.

    make gen-secrets                 list what is missing, confirm, create it
    make gen-secrets GEN_ARGS=--dry-run    only list (names)

Idempotent: a key that exists is NEVER read for overwriting and never changed; only
missing keys are created. Values are generated in memory and sent straight to
Infisical; nothing is printed, logged or written to disk. Derived keys (Argon2id /
bcrypt hashes of a generated login) read their source value from Infisical in memory.
Confirmation: type "yes", or AUTO_APPROVE=1. G.A.R.T.H. may run this.
"""

from __future__ import annotations

import base64
import os
import secrets as rnd
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from secrets_check import load_manifest  # noqa: E402


def generate(spec: str, read_source) -> str:
    kind, _, arg = spec.partition(":")
    if kind == "hex":
        return rnd.token_hex(int(arg))
    if kind == "base64":
        # URL-safe alphabet, no padding: safe in env vars, config files and URLs.
        return base64.urlsafe_b64encode(rnd.token_bytes(int(arg))).decode().rstrip("=")
    if kind == "literal":
        return arg
    if kind == "empty":
        return ""
    if kind == "argon2id-of":
        from argon2 import PasswordHasher  # pinned in scripts/install-tools.sh
        # Vaultwarden's `vaultwarden hash` default ("bitwarden" preset): m=65540 KiB, t=3, p=4.
        return PasswordHasher(time_cost=3, memory_cost=65540, parallelism=4).hash(read_source(arg))
    if kind == "bcrypt-b64-of":
        import bcrypt  # pinned in scripts/install-tools.sh
        # Backrest's format: base64(bcrypt hash).
        h = bcrypt.hashpw(read_source(arg).encode(), bcrypt.gensalt(rounds=10))
        return base64.b64encode(h).decode()
    raise SystemExit(f"unknown generate spec {spec!r}")


def confirm(n: int) -> bool:
    if os.environ.get("AUTO_APPROVE") == "1":
        return True
    if not sys.stdin.isatty():
        print("refusing without confirmation (terminal, or AUTO_APPROVE=1)", file=sys.stderr)
        return False
    return input(f"\n>>> Create these {n} secrets in Infisical? Type \"yes\": ").strip() == "yes"


def main() -> None:
    from infisical_exec import client, load_local_env

    dry = "--dry-run" in sys.argv
    load_local_env()
    folders, manifest = load_manifest()
    c, cfg = client()
    project, env = cfg["infisical_project_id"], cfg["infisical_env"]

    existing: dict[str, set[str]] = {}
    for folder in manifest:
        try:
            res = c.secrets.list_secrets(project_id=project, environment_slug=env, secret_path=folder,
                                         view_secret_value=False, expand_secret_references=False,
                                         include_imports=False)
            existing[folder] = {s.secretKey for s in res.secrets}
        except Exception:  # noqa: BLE001 (missing folder)
            sys.exit(f"folder {folder} missing in Infisical: run `make secrets-folders` first")

    todo = [(f, k, m["generate"]) for f, keys in manifest.items() for k, m in keys.items()
            if m.get("by") == "generated" and k not in existing[f]]
    # Plain values first, then hashes of them (their sources may be created in this run).
    todo.sort(key=lambda x: "-of:" in x[2])
    print(f"Infisical {cfg['infisical_host']} project {cfg.get('infisical_project_slug')} env {env}")
    if not todo:
        print("nothing to generate: every `generated` key exists")
        return
    print(f"{len(todo)} generated secret(s) missing (names only):")
    for f, k, spec in todo:
        print(f"  + {f}/{k}  ({spec.split(':')[0]})")
    if dry or not confirm(len(todo)):
        return

    def read_source(path: str) -> str:
        folder, _, key = path.rpartition("/")
        s = c.secrets.get_secret_by_name(secret_name=key, project_id=project, environment_slug=env,
                                         secret_path=folder, view_secret_value=True,
                                         expand_secret_references=False, include_imports=False)
        return s.secretValue

    for f, k, spec in todo:
        value = generate(spec, read_source)
        c.secrets.create_secret_by_name(secret_name=k, project_id=project, environment_slug=env,
                                        secret_path=f, secret_value=value,
                                        secret_comment=f"generated by make gen-secrets ({spec.split(':')[0]})")
        del value
        print(f"  created {f}/{k}")
    print("done. Logins for people are in Infisical /operator (copy them to your password manager).")


if __name__ == "__main__":
    main()
